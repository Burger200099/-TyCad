#!/usr/bin/env python3
"""Writes src/UPartsSchema.pas: the schema of docs/parts_schema.sql and the starting taxonomy of docs/parts_seed.py (classes, fields, kinds, rating quantities;
no parts, no products) as Pascal string constants, so the program can create a new parts file (File: Parts > New Parts Library).
Run it again whenever docs/parts_schema.sql or the taxonomy in parts_seed.py changes (and keep PARTS_SCHEMA_CURRENT of UPartsDb in step)."""
import os, sqlite3, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, "..")
sys.path.insert(0, os.path.join(ROOT, "docs"))
import parts_seed

def split(sql):
    out, cur = [], ""
    for line in sql.split("\n"):
        cur += line + "\n"
        if sqlite3.complete_statement(cur):
            out.append(cur)
            cur = ""
    rest = cur.strip()
    assert not rest or all(l.strip().startswith("--") or not l.strip() for l in rest.split("\n")), rest
    return out

def strip_lead(stmt):
    lines = stmt.split("\n")
    while lines and (not lines[0].strip() or lines[0].strip().startswith("--")):
        lines.pop(0)
    return "\n".join(lines).rstrip()

def lit(s):
    parts = s.split("\n")
    return " + #10 +\n    ".join("'" + p.replace("'", "''") + "'" for p in parts)

def q(v):
    if v is None: return "NULL"
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

schema = [strip_lead(s) for s in split(open(os.path.join(ROOT, "docs", "parts_schema.sql"), encoding="utf-8").read())]
schema = [s for s in schema if s and not s.upper().startswith("PRAGMA FOREIGN_KEYS")]
tmp = os.path.join(tempfile.mkdtemp(), "seed.db"); c = parts_seed.build(tmp)
ins = []
for t, cols in (("PartClass", "ClassID,ParentID,Name,Abstract,Description"), ("FieldDef", "FieldID,ClassID,Name,Type,Unit,EnumValues,Required,Description"),
                ("ObjectKind", "KindID,ParentID,Name,Abstract,Description"), ("KindFieldDef", "FieldID,KindID,Name,Type,Unit,EnumValues,Required,Description"),
                ("ClassAllowsKind", None), ("RatingQuantity", "Name,Unit,Sense,Description")):
    cur = c.execute("select %s from %s order by rowid" % (cols or "*", t))
    names = cols or ",".join(r[1] for r in c.execute("pragma table_info(%s)" % t))
    for row in cur:
        ins.append("INSERT INTO %s(%s) VALUES (%s)" % (t, names, ",".join(q(v) for v in row)))
c.close()
o = ["{ UPartsSchema - GENERATED by tools/gen_partsschema.py from docs/parts_schema.sql and the taxonomy of docs/parts_seed.py. Do not edit by hand.",
     "  PARTS_SCHEMA_SQL are the statements that make an empty parts file; PARTS_STARTER_SQL fill it with the starting classes, fields, child kinds and rating",
     "  quantities (no parts, no products). }", "unit UPartsSchema;", "", "{$mode objfpc}{$H+}", "", "interface", "",
     "const", "  PARTS_SCHEMA_SQL: array[0..%d] of String = (" % (len(schema) - 1)]
o.append(",\n".join("    " + lit(s) for s in schema))
o.append("  );")
o.append("")
o.append("  PARTS_STARTER_SQL: array[0..%d] of String = (" % (len(ins) - 1))
o.append(",\n".join("    " + lit(s) for s in ins))
o.append("  );")
o += ["", "implementation", "", "end."]
open(os.path.join(ROOT, "src", "UPartsSchema.pas"), "w", encoding="utf-8", newline="\n").write("\n".join(o) + "\n")
print("UPartsSchema.pas:", len(schema), "schema statements,", len(ins), "starter rows")
